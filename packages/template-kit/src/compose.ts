import { stringify } from "yaml";

export type DependsOnCondition =
  | "service_started"
  | "service_healthy"
  | "service_completed_successfully";

/** The subset of the Compose service spec templates use. Unknown keys pass through. */
export interface ComposeService {
  image?: string;
  build?: string | { context: string; dockerfile?: string };
  command?: string[];
  entrypoint?: string[];
  environment?: Record<string, string>;
  depends_on?: Record<string, { condition: DependsOnCondition }>;
  ports?: string[];
  volumes?: string[];
  healthcheck?: {
    test: string[];
    interval?: string;
    timeout?: string;
    retries?: number;
    start_period?: string;
  };
  restart?: string;
  [key: string]: unknown;
}

export interface ComposeFile {
  name?: string;
  services: Record<string, ComposeService>;
  volumes?: Record<string, Record<string, unknown>>;
}

/**
 * What one template contributes. A fragment may name services owned by other templates (for
 * example `uses-database` adds `DATABASE_URL` to the consuming service); fragments are deep-merged.
 */
export interface ComposeFragment {
  services?: Record<string, ComposeService>;
  volumes?: Record<string, Record<string, unknown>>;
}

export class ComposeConflictError extends Error {
  constructor(readonly path: string) {
    super(`Templates disagree about docker-compose value ${path}`);
    this.name = "ComposeConflictError";
  }
}

/**
 * Deep-merges fragments. Objects merge key by key, arrays are concatenated without duplicates,
 * and two different scalars at the same path throw `ComposeConflictError`.
 */
export function mergeCompose(fragments: ComposeFragment[], name?: string): ComposeFile {
  let merged: Record<string, unknown> = { services: {} };
  for (const fragment of fragments) merged = mergeValue(merged, fragment, "") as typeof merged;
  const file = merged as unknown as ComposeFile;
  return name === undefined ? file : { name, ...file };
}

function mergeValue(a: unknown, b: unknown, path: string): unknown {
  if (b === undefined) return a;
  if (a === undefined) return b;
  if (Array.isArray(a) && Array.isArray(b)) {
    const out = [...a];
    const seen = new Set(a.map((item) => JSON.stringify(item)));
    for (const item of b) {
      const key = JSON.stringify(item);
      if (!seen.has(key)) out.push(item);
      seen.add(key);
    }
    return out;
  }
  if (isPlainObject(a) && isPlainObject(b)) {
    const out: Record<string, unknown> = { ...a };
    for (const [key, value] of Object.entries(b)) {
      out[key] = mergeValue(out[key], value, path ? `${path}.${key}` : key);
    }
    return out;
  }
  if (JSON.stringify(a) === JSON.stringify(b)) return a;
  throw new ComposeConflictError(path);
}

function isPlainObject(value: unknown): value is Record<string, unknown> {
  return typeof value === "object" && value !== null && !Array.isArray(value);
}

/** Maps whose key order is irrelevant are sorted so the output doesn't depend on merge order. */
const SORTED_MAPS = new Set(["services", "volumes", "environment", "depends_on"]);

/** Serializes a compose file deterministically, with a do-not-edit header. */
export function composeToYaml(file: ComposeFile): string {
  const header = "# Generated by Jeeves. Do not edit: regenerate from the design instead.\n";
  return header + stringify(sortMaps(file), { lineWidth: 0 });
}

function sortMaps(value: unknown, key?: string): unknown {
  if (Array.isArray(value)) return value.map((item) => sortMaps(item));
  if (!isPlainObject(value)) return value;
  const entries = Object.entries(value).map(([k, v]) => [k, sortMaps(v, k)] as const);
  if (key !== undefined && SORTED_MAPS.has(key)) entries.sort(([x], [y]) => (x < y ? -1 : 1));
  return Object.fromEntries(entries);
}
