import { describe, expect, it } from "vitest";
import { parse } from "yaml";
import { ComposeConflictError, composeToYaml, mergeCompose } from "./compose.ts";

describe("mergeCompose", () => {
  it("merges fragments that name the same service", () => {
    const merged = mergeCompose([
      { services: { api: { image: "node:24", environment: { PORT: "8080" }, ports: ["8080"] } } },
      {
        services: {
          api: {
            environment: { DATABASE_URL: "postgres://db" },
            depends_on: { db: { condition: "service_healthy" } },
            ports: ["8080", "9090"],
          },
          db: { image: "postgres:17-alpine" },
        },
        volumes: { "db-data": {} },
      },
    ]);
    expect(merged).toEqual({
      services: {
        api: {
          image: "node:24",
          environment: { PORT: "8080", DATABASE_URL: "postgres://db" },
          ports: ["8080", "9090"],
          depends_on: { db: { condition: "service_healthy" } },
        },
        db: { image: "postgres:17-alpine" },
      },
      volumes: { "db-data": {} },
    });
  });

  it("refuses two templates setting the same value differently", () => {
    const run = () =>
      mergeCompose([
        { services: { api: { environment: { DATABASE_URL: "a" } } } },
        { services: { api: { environment: { DATABASE_URL: "b" } } } },
      ]);
    expect(run).toThrow(ComposeConflictError);
    expect(run).toThrow("services.api.environment.DATABASE_URL");
  });

  it("accepts identical values from several fragments", () => {
    const fragment = { services: { db: { image: "postgres:17-alpine" } } };
    expect(mergeCompose([fragment, fragment]).services.db?.image).toBe("postgres:17-alpine");
  });
});

describe("composeToYaml", () => {
  it("is independent of fragment order and round-trips", () => {
    const a = { services: { web: { image: "w", environment: { B: "2", A: "1" } } } };
    const b = { services: { api: { image: "a" } }, volumes: { z: {}, y: {} } };
    const yaml = composeToYaml(mergeCompose([a, b]));
    expect(composeToYaml(mergeCompose([b, a]))).toBe(yaml);
    expect(yaml.startsWith("# Generated by Jeeves.")).toBe(true);
    expect(yaml.indexOf("api:")).toBeLessThan(yaml.indexOf("web:"));
    expect(yaml.indexOf("A: ")).toBeLessThan(yaml.indexOf("B: "));
    expect(parse(yaml)).toEqual(mergeCompose([a, b]));
  });
});
