import type { ResourceConfig } from "@jeeves/spec";
import { type DesignDocument, resolveConfig } from "@jeeves/spec";
import { type OutputFile, type TemplateModule, VENDOR_DIR } from "@jeeves/template-kit";
import type { AcceptanceRegistration } from "./acceptance.ts";
import type { PlannedElement, Subject } from "./plan.ts";

/** A subject with the module that generates it, for the element notes. */
export interface SubjectSummary extends Subject {
  module: TemplateModule;
}

export const DESIGN_PATH = "jeeves/design.json";
export const LOCK_PATH = "jeeves/lock.json";
export const elementNotesPath = (id: string) => `jeeves/elements/${id}.md`;

const generated = (path: string, contents: string): OutputFile => ({
  path,
  contents,
  ownership: "generated",
});
const scaffold = (path: string, contents: string): OutputFile => ({
  path,
  contents,
  ownership: "scaffold",
});

/** The design snapshot this generation used. */
export function designFile(design: DesignDocument): OutputFile {
  return generated(DESIGN_PATH, `${JSON.stringify(design, null, 2)}\n`);
}

const DO_NOT_EDIT =
  "<!-- Generated by Jeeves from the design. Do not edit; regenerate instead. -->";

export interface OwnershipContext {
  resourceModels?: Record<string, ResourceConfig>;
  fixedAcceptance?: AcceptanceRegistration[];
}

/** Rules for coding agents working in the project (PLAN §9). */
export function agentsFile(
  design: DesignDocument,
  elements: PlannedElement[],
  projectName: string,
  context: OwnershipContext = {},
): OutputFile {
  const models = context.resourceModels ?? {};
  const rows = elements.map((planned) => {
    const element = design.elements.find((e) => e.id === planned.id);
    return `| \`${planned.id}\` | ${cell(element?.name ?? planned.id)} | \`${planned.template}\` | \`${planned.dir}/\` | [notes](${elementNotesPath(planned.id)}) |`;
  });
  const structured = elements.filter((element) => models[element.id]);
  const generatedPaths = new Set([
    "`docker-compose.yml`",
    "`jeeves/`",
    "`AGENTS.md`",
    "every `*.generated.ts`",
    "every `src/clients/*.openapi.ts`",
  ]);
  for (const element of structured) {
    generatedPaths.add(`\`${element.dir}/src/generated/**\``);
    generatedPaths.add(`\`${element.dir}/resource-migrations/**\``);
    generatedPaths.add(`\`tests/generated/${element.id}/**\``);
    generatedPaths.add(`\`tests/acceptance/${element.id}/**\``);
    generatedPaths.add(`\`contracts/${element.id}.openapi.yaml\``);
  }
  for (const service of new Set((context.fixedAcceptance ?? []).map((suite) => suite.service)))
    generatedPaths.add(`\`tests/acceptance/${service}/**\``);
  const fixed = context.fixedAcceptance ?? [];
  return generated(
    "AGENTS.md",
    `${DO_NOT_EDIT}

# ${projectName}: rules for coding agents

This is a Jeeves template project. Every element of the design is an instantiated template that
already builds, starts, and passes its template tests. Your job is to implement features inside
the extension points the templates give you, not to change the templates.

## Elements

| ID | Name | Template | Directory | Notes and guide |
| --- | --- | --- | --- | --- |
${rows.join("\n")}

Each element's notes file holds what to build (the implementation notes from the design), the
generated standard behavior it must not reimplement, and the template's agent guide (where code
goes and what not to touch). Read it before changing the element.

## Ownership

- **Generated-owned files** are listed with their hashes in \`jeeves/lock.json\`. Never edit
  them. For this project that includes ${[...generatedPaths].join(", ")}.
- **\`${VENDOR_DIR}/\`** holds the template runtimes. Never edit or replace them.
${
  structured.length > 0
    ? `- **Structured resource services are generated-owned:** ${structured
        .map(
          (element) =>
            `\`${element.id}\` (contract \`contracts/${element.id}.openapi.yaml\`, generated routes and resource descriptors, \`${element.dir}/resource-migrations/\`, \`tests/generated/${element.id}/\`, \`tests/acceptance/${element.id}/\`)`,
        )
        .join(
          "; ",
        )}. Do **not** edit the contract, generated routes, resource migrations, generated tests, or fixed acceptance tests. Implement only the declared extension in \`${structured[0]?.dir ?? "services/<service>"}/src/features/<extension-id>/\`; each extension task names its own directory and operation.
- **Fixed project acceptance** under \`tests/acceptance/\` (${fixed.length ? fixed.map((suite) => `\`${suite.service}/${suite.id}\``).join(", ") : "when present"}) is generated-owned and protected. Agents may add supplemental tests elsewhere, but cannot redefine expected behavior.
`
    : ""
}- **Everything else is project-owned**: feature code, supplemental tests, \`package.json\`
  files, Dockerfiles${
    structured.length > 0
      ? ", and any API contract for an element that has no structured resource model"
      : ", and API contracts in `contracts/`"
  }. Change it freely, within the element you were asked to work on.
- Stay inside the element's directory, plus the contracts that element owns. If the task needs a
  change elsewhere, stop and say so.

## Checks

Jeeves runs these after every task; run them yourself before you finish:

\`\`\`sh
pnpm install
pnpm typecheck
pnpm test
docker compose up --build --wait
\`\`\`

The template test packs run against the composed project and must stay green. Add supplemental
tests for what you build next to the element (\`tests/\`), or in \`tests/e2e/\` for flows across
elements.

## Dependencies

Pin exact versions. Don't add a dependency that duplicates what a template runtime already does.
`,
  );
}

function cell(text: string): string {
  return text.replaceAll("|", "\\|").replaceAll("\n", " ");
}

/** `jeeves/elements/<id>.md`: implementation notes and template agent guides (orchestrator input). */
export function elementNotesFile(
  design: DesignDocument,
  planned: PlannedElement,
  subjects: SubjectSummary[],
): OutputFile {
  const element = design.elements.find((e) => e.id === planned.id);
  if (!element) throw new Error(`No element "${planned.id}"`);
  const mine = subjects.filter((s) => s.element === element.id);
  const nameOf = (id: string) => design.elements.find((e) => e.id === id)?.name ?? id;
  const end = (e: { element: string; attachment?: string }) =>
    `${nameOf(e.element)} (\`${e.element}\`${e.attachment ? `, attachment \`${e.attachment}\`` : ""})`;

  const lines: string[] = [DO_NOT_EDIT, "", `# ${element.name}`, ""];
  lines.push(`- ID: \`${element.id}\``);
  lines.push(`- Template: \`${planned.template}\``);
  lines.push(`- Directory: \`${planned.dir}/\``);
  lines.push(`- Owned paths: ${planned.ownedPaths.map((p) => `\`${p}\``).join(", ")}`);
  lines.push("", "## Implementation notes", "", notesOrNone(element.notes), "");

  const model = structuredModel(element);
  if (model) {
    lines.push(
      "## Generated standard behavior (do not reimplement)",
      "",
      "This service's resource model generates sessions and owner-scoped CRUD routes from its fixed",
      "contract. Do not add standard CRUD handlers, routes, tables, or migrations; implement only the",
      "declared extensions below.",
      "",
      `- Resources: ${model.resources.map((r) => `\`${r.name}\` (${r.access}; ${r.operations.length ? r.operations.join(", ") : "no CRUD routes"})`).join("; ")}`,
      `- Extensions: ${model.extensions.map((e) => `\`${e.id}\` ${e.method} ${e.path} (${e.access}; ${e.acceptance.join(", ")})`).join("; ")}`,
      `- Fixed acceptance: ${model.acceptanceCases.length ? model.acceptanceCases.join(", ") : "none"}`,
      `- Generated-owned: \`contracts/${element.id}.openapi.yaml\`, \`${planned.dir}/src/generated/\`, \`${planned.dir}/resource-migrations/\`, \`tests/generated/${element.id}/\`, \`tests/acceptance/${element.id}/\``,
      `- Implement extensions in \`${planned.dir}/src/features/<extension-id>/\`. Read the generated`,
      "  resource descriptors in `src/generated/resources/` for physical table and column names.",
      "  Use `database.pool` from `src/jeeves.generated.ts`, `sessionPrincipal(request.request)` for the",
      "  authenticated owner, and `publicOrigin()` for the validated deployment origin.",
      "",
    );
  }

  const guides = new Set<string>();
  for (const subject of mine) {
    if (guides.has(subject.template)) continue;
    guides.add(subject.template);
    const structured = subject.template.startsWith("rest-api-server@") && model !== undefined;
    lines.push(
      "---",
      "",
      `<!-- Agent guide for ${subject.template}${structured ? " (structured resource model)" : ""} -->`,
      "",
    );
    if (structured)
      lines.push(
        "> This service has a structured resource model. The contract, generated routes, resource",
        "> descriptors, resource migrations, generated tests, and fixed acceptance tests are",
        "> generated-owned. Implement only the declared extension named by your task.",
        "",
      );
    lines.push(subject.module.agentGuide.trim(), "");
  }

  const elementModule = mine.find((s) => s.attachment === undefined)?.module;
  if (elementModule) {
    lines.push(
      "## Config",
      "",
      fencedJson(resolveConfig(manifestConfig(elementModule), element.config)),
      "",
    );
  }

  if (element.attachments.length > 0) {
    lines.push("## Attachments", "");
    for (const attachment of element.attachments) {
      const subject = mine.find((s) => s.attachment === attachment.id);
      lines.push(
        `### \`${attachment.id}\` (\`${subject?.template ?? attachment.template.id}\`)`,
        "",
      );
      if (subject) {
        lines.push(
          fencedJson(resolveConfig(manifestConfig(subject.module), attachment.config)),
          "",
        );
      }
      lines.push(notesOrNone(attachment.notes), "");
    }
  }

  const outgoing = design.connections.filter((c) => c.from.element === element.id);
  const incoming = design.connections.filter((c) => c.to.element === element.id);
  if (outgoing.length + incoming.length > 0) {
    lines.push("## Connections", "");
    for (const c of outgoing) lines.push(`- ${end(c.from)} **${c.kind}** ${end(c.to)}`);
    for (const c of incoming) lines.push(`- ${end(c.from)} **${c.kind}** ${end(c.to)}`);
    lines.push("");
  }

  return generated(elementNotesPath(element.id), `${lines.join("\n").trimEnd()}\n`);
}

function structuredModel(element: {
  attachments: { template: { id: string }; config: Record<string, unknown> }[];
}): ResourceConfig | undefined {
  const attachment = element.attachments.find(
    (a) => a.template.id === "rest-api-server" && a.config.model,
  );
  return attachment?.config.model as ResourceConfig | undefined;
}

function manifestConfig(module: TemplateModule) {
  // `resolveConfig` takes the parsed manifest's config schema; modules hold the input form,
  // which is the same Zod object.
  return module.manifest.config as Parameters<typeof resolveConfig>[0];
}

function notesOrNone(notes: string): string {
  return notes.trim() ? notes.trim() : "_No implementation notes._";
}

function fencedJson(value: unknown): string {
  return `\`\`\`json\n${JSON.stringify(value, null, 2)}\n\`\`\``;
}

/** npm package name for the project root: lowercase, URL-safe. */
export function packageName(projectName: string): string {
  const slug = projectName
    .toLowerCase()
    .replaceAll(/[^a-z0-9]+/g, "-")
    .replaceAll(/^-+|-+$/g, "");
  return slug || "jeeves-project";
}

/** Project-owned files at the root, written once. */
export function rootScaffoldFiles(projectName: string): OutputFile[] {
  const pkg = {
    name: packageName(projectName),
    private: true,
    version: "0.1.0",
    type: "module",
    packageManager: "pnpm@12.16.1",
    engines: { node: ">=24" },
    scripts: {
      typecheck: "pnpm -r --no-bail typecheck",
      test: "pnpm -r --no-bail test",
      up: "docker compose up --build --wait",
      down: "docker compose down",
    },
  };
  return [
    scaffold("package.json", `${JSON.stringify(pkg, null, 2)}\n`),
    scaffold(
      "pnpm-workspace.yaml",
      `packages:
  - services/*
  - frontends/*
  - packages/*

# Install scripts that generated elements need (Vite's bundler and Drizzle Kit use esbuild).
allowBuilds:
  esbuild: true
`,
    ),
    scaffold(
      ".gitignore",
      `node_modules/
dist/
coverage/
test-results/
playwright-report/
*.tsbuildinfo
.env
.env.local
# Client types are regenerated from the contracts by each element's \`pretypecheck\` script.
**/src/clients/*.openapi.ts
`,
    ),
    scaffold(
      "tests/e2e/README.md",
      `# End-to-end tests

Project-owned tests for flows across elements go here. Jeeves runs each template's test pack
against the composed project itself (after generation and after every orchestration task), so
those checks don't live in this folder.
`,
    ),
  ];
}
