/** Release 0.1.0: original deterministic configuration, not a new HTTP proxy implementation. */
import { z } from "zod";

export const HTTP_POOL_VERSION = "0.1.0";
export const HTTP_POOL_IMAGE =
  "haproxy:3.4.7-alpine3.24@sha256:2caaf8b1a1ef67f3f1ea9b721f2821675d3ba4500fb518e23884fecb93e8dbaa";
export const httpPoolSchema = z.strictObject({
  serviceId: z
    .string()
    .min(1)
    .max(40)
    .regex(/^[a-z][a-z0-9]*(?:-[a-z0-9]+)*$/),
  port: z.int().min(1024).max(65535).default(8080),
  replicas: z.union([z.literal(2), z.literal(3)]).default(2),
});
export type HttpPoolInput = z.input<typeof httpPoolSchema>;

export function createHttpPool(input: HttpPoolInput) {
  const config = httpPoolSchema.parse(input);
  const instances = Array.from(
    { length: config.replicas },
    (_, index) => `${config.serviceId}-instance-${index + 1}`,
  );
  const configurationPath = `infrastructure/http-pools/${config.serviceId}/haproxy.cfg`;
  const descriptor = {
    schemaVersion: 1 as const,
    version: HTTP_POOL_VERSION,
    ...config,
    instances,
    proxyImage: HTTP_POOL_IMAGE,
    balance: "roundrobin" as const,
    proxyRetries: 0,
    backendDatabasePoolMax: 5,
    proxy: {
      cpus: 0.5,
      memoryMiB: 128,
      pids: 64,
      maxConnections: 256,
      shutdownSeconds: 30,
      dockerGraceSeconds: 35,
    },
    backend: { maxConnections: 64, maxQueue: 64 },
    timeouts: {
      connectMs: 2000,
      queueMs: 2000,
      requestHeadersMs: 10000,
      idleMs: 30000,
      keepAliveMs: 5000,
    },
    readiness: { path: "/ready", intervalMs: 1000, fall: 2, rise: 2, minimumAvailable: 1 },
  };
  const configuration = `# Generated by @jeeves/http-pool 0.1.0. Change the definition, not this file.
global
  log stdout format raw local0 warning
  nbthread 1
  maxconn 256
  hard-stop-after 30s
  stats socket /tmp/jeeves-pool.sock mode 600 level user

defaults
  mode http
  log global
  option dontlog-normal
  option http-server-close
  retries 0
  retry-on none
  no option redispatch
  timeout connect 2s
  timeout queue 2s
  timeout client 30s
  timeout server 30s
  timeout http-request 10s
  timeout http-keep-alive 5s
  timeout check 2s
  timeout tunnel 30s

resolvers docker
  nameserver embedded 127.0.0.11:53
  resolve_retries 3
  timeout resolve 1s
  timeout retry 1s
  hold valid 1s
  hold nx 1s
  hold refused 1s
  hold other 1s
  hold timeout 1s
  hold obsolete 0s

frontend application
  bind :${config.port}
  http-request del-header Forwarded
  http-request del-header X-Forwarded-For
  http-request del-header X-Forwarded-Host
  http-request del-header X-Forwarded-Proto
  http-request del-header X-Real-IP
  http-request return status 200 content-type application/json string '{"status":"ok"}' if { path -i /health } { method GET HEAD }
  http-request return status 503 content-type application/json string '{"status":"not-ready"}' if { path -i /ready } { method GET HEAD } { nbsrv(application_instances) lt 1 }
  http-request return status 200 content-type application/json string '{"status":"ready"}' if { path -i /ready } { method GET HEAD }
  default_backend application_instances

backend application_instances
  balance roundrobin
  option httpchk
  http-check send meth GET uri /ready ver HTTP/1.1 hdr Host localhost
  http-check expect status 200
${instances.map((name, index) => `  server instance${index + 1} ${name}:${config.port} check resolvers docker resolve-prefer ipv4 init-addr libc,none init-state fully-down inter 1s fall 2 rise 2 maxconn 64 maxqueue 64`).join("\n")}
`;
  return {
    descriptor,
    configurationPath,
    configuration,
    proxyCompose: {
      image: HTTP_POOL_IMAGE,
      user: "99:99",
      ports: [`127.0.0.1::${config.port}`],
      volumes: [`./${configurationPath}:/usr/local/etc/haproxy/haproxy.cfg:ro`],
      read_only: true,
      tmpfs: ["/tmp:rw,noexec,nosuid,size=4m"],
      cap_drop: ["ALL"],
      security_opt: ["no-new-privileges:true"],
      cpus: descriptor.proxy.cpus,
      mem_limit: "128m",
      pids_limit: descriptor.proxy.pids,
      init: true,
      restart: "on-failure:3",
      stop_signal: "SIGUSR1",
      stop_grace_period: "35s",
      healthcheck: {
        test: ["CMD", "wget", "-q", "-O", "/dev/null", `http://127.0.0.1:${config.port}/ready`],
        interval: "2s",
        timeout: "3s",
        retries: 15,
        start_period: "30s",
      },
      depends_on: Object.fromEntries(
        instances.map((name) => [name, { condition: "service_started" as const }]),
      ),
    },
  };
}
export type HttpPool = ReturnType<typeof createHttpPool>;
