import { fileURLToPath } from "node:url";
import type {
  ComposeService,
  GenerateContext,
  GenerateResult,
  OutputFile,
} from "@jeeves/template-kit";
import { renderScaffold } from "@jeeves/template-kit";

const CONSUMER_SCAFFOLD = fileURLToPath(new URL("./scaffold/consumer", import.meta.url));

/**
 * Local-only credentials. The database is reachable from the host on 127.0.0.1 alone, and
 * generated output must be deterministic, so passwords are fixed rather than random.
 */
export const SUPERUSER = { user: "postgres", password: "postgres" } as const;

/** Kept equal to the runtime's `drizzle-orm`, so a service gets one copy. */
export const DRIZZLE_ORM_VERSION = "0.45.4";
export const DRIZZLE_KIT_VERSION = "0.31.11";

export function consumerPassword(consumerId: string): string {
  return `${consumerId}-local`;
}

export function consumerDatabaseUrl(databaseId: string, consumerId: string): string {
  return `postgres://${consumerId}:${consumerPassword(consumerId)}@${databaseId}:5432/${consumerId}`;
}

/** The one-shot compose service that applies `init/*.sql` on every `docker compose up`. */
export function initServiceName(databaseId: string): string {
  return `${databaseId}-init`;
}

export interface Consumer {
  id: string;
  name: string;
  dir: string;
}

/** Elements with a `uses-database` connection to this database, by ID, without duplicates. */
export function consumersOf(ctx: GenerateContext): Consumer[] {
  const byId = new Map<string, Consumer>();
  for (const { connection, peer } of ctx.incoming) {
    if (connection.kind !== "uses-database" || peer.dir === undefined) continue;
    byId.set(peer.element.id, { id: peer.element.id, name: peer.element.name, dir: peer.dir });
  }
  return [...byId.values()].sort((a, b) => (a.id < b.id ? -1 : 1));
}

/**
 * Idempotent psql script: one login role and one database per consumer, each database closed to
 * everyone but its owner. It runs on every `up`, so consumers added after the volume was created
 * still get their database. IDs are slugs, so quoting them as identifiers is enough.
 */
export function initSql(databaseId: string, consumers: Consumer[]): string {
  const lines = [
    `-- Generated by Jeeves for the "${databaseId}" postgres element. Do not edit.`,
    `-- Applied by the ${initServiceName(databaseId)} job on every \`docker compose up\`, so every`,
    "-- statement must be safe to run again.",
    "",
    "REVOKE CONNECT ON DATABASE postgres FROM PUBLIC;",
    "REVOKE CONNECT ON DATABASE template1 FROM PUBLIC;",
  ];
  for (const { id, name } of consumers) {
    lines.push(
      "",
      `-- ${name}`,
      `SELECT 'CREATE ROLE "${id}"' WHERE NOT EXISTS (SELECT FROM pg_roles WHERE rolname = '${id}')\\gexec`,
      `ALTER ROLE "${id}" WITH LOGIN NOSUPERUSER NOCREATEDB NOCREATEROLE PASSWORD '${consumerPassword(id)}';`,
      `SELECT 'CREATE DATABASE "${id}" OWNER "${id}"' WHERE NOT EXISTS (SELECT FROM pg_database WHERE datname = '${id}')\\gexec`,
      `REVOKE CONNECT ON DATABASE "${id}" FROM PUBLIC;`,
      `GRANT CONNECT ON DATABASE "${id}" TO "${id}";`,
    );
  }
  return `${lines.join("\n")}\n`;
}

export function generate(ctx: GenerateContext): GenerateResult {
  const id = ctx.element.id;
  const init = initServiceName(id);
  if (ctx.design.elements.some((e) => e.id === init)) {
    throw new Error(`Element "${init}" clashes with the init job of postgres element "${id}"`);
  }
  const version = String(ctx.config.version);
  const image = `postgres:${version}-alpine`;
  const consumers = consumersOf(ctx);

  const files: OutputFile[] = [
    {
      path: `${ctx.dir}/init/10-consumers.sql`,
      contents: initSql(id, consumers),
      ownership: "generated",
    },
  ];
  for (const consumer of consumers) {
    files.push(
      ...renderScaffold(CONSUMER_SCAFFOLD, consumer.dir, {
        consumerName: consumer.name,
        databaseName: ctx.element.name,
      }),
    );
  }

  const services: Record<string, ComposeService> = {
    [id]: {
      image,
      environment: { POSTGRES_USER: SUPERUSER.user, POSTGRES_PASSWORD: SUPERUSER.password },
      // An ephemeral host port on loopback: reachable for tests and tools, never from the network,
      // and two projects can run side by side.
      ports: ["127.0.0.1::5432"],
      volumes: [`${id}-data:/var/lib/postgresql/data`],
      healthcheck: {
        test: ["CMD-SHELL", `pg_isready -U ${SUPERUSER.user} -d postgres`],
        interval: "2s",
        timeout: "3s",
        retries: 30,
      },
      restart: "unless-stopped",
    },
    [init]: {
      image,
      depends_on: { [id]: { condition: "service_healthy" } },
      environment: { PGHOST: id, PGUSER: SUPERUSER.user, PGPASSWORD: SUPERUSER.password },
      volumes: [`./${ctx.dir}/init:/jeeves-init:ro`],
      entrypoint: ["sh", "-c"],
      // `$$` is Compose's escape for a literal `$`.
      command: [
        'for f in /jeeves-init/*.sql; do psql -v ON_ERROR_STOP=1 -q -f "$$f" || exit 1; done',
      ],
      restart: "no",
    },
  };
  for (const consumer of consumers) {
    services[consumer.id] = {
      environment: { DATABASE_URL: consumerDatabaseUrl(id, consumer.id) },
      depends_on: {
        [id]: { condition: "service_healthy" },
        [init]: { condition: "service_completed_successfully" },
      },
    };
  }

  return {
    files,
    compose: { services, volumes: { [`${id}-data`]: {} } },
    runtimeDependencies: consumers.map((c) => ({
      element: c.id,
      name: "@jeeves/postgres-runtime",
    })),
    // The consumer scaffold's schema.ts and drizzle.config.ts use these directly.
    packageDependencies: consumers.flatMap((c) => [
      { element: c.id, name: "drizzle-orm", version: DRIZZLE_ORM_VERSION },
      { element: c.id, name: "drizzle-kit", version: DRIZZLE_KIT_VERSION, dev: true },
    ]),
  };
}
