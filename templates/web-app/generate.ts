import { fileURLToPath } from "node:url";
import type { ComposeService, GenerateContext, GenerateResult } from "@jeeves/template-kit";
import {
  apiEnvName,
  clientExportName,
  renderScaffold,
  restClientTargets,
} from "@jeeves/template-kit";

const SCAFFOLD = fileURLToPath(new URL("./scaffold/app", import.meta.url));

/** Where the browser reaches an API: the app's own server, which forwards to the service. */
export function apiPath(targetId: string): string {
  return `/_api/${targetId}`;
}

/** The compose health check: nginx answers `/healthz` once it's serving. */
export function healthcheck(port: number): ComposeService["healthcheck"] {
  return {
    test: ["CMD", "wget", "-q", "-O", "/dev/null", `http://127.0.0.1:${port}/healthz`],
    interval: "2s",
    timeout: "3s",
    retries: 15,
    start_period: "30s",
  };
}

/** A placeholder envsubst fills from the environment when the container starts: `${NAME}`. */
export function envRef(name: string): string {
  return `\${${name}}`;
}

const HEADER =
  "Generated by Jeeves from the design. Do not edit: it's rewritten on every generation.";

/** `src/jeeves.generated.ts`: the app definition with its API clients. */
export function wiringSource(ctx: GenerateContext): string {
  const { element, config } = ctx;
  const q = (value: unknown) => JSON.stringify(value);
  const c = (text: string) => text.replaceAll("*/", "* /");
  const targets = restClientTargets(ctx).map((t) => t.target.id);
  return [
    `// ${HEADER}`,
    "// To change the wiring, change the design (attachments, connections, config) and regenerate.",
    'import { defineApp } from "@jeeves/web-runtime";',
    ...targets.map(
      (id) => `import { ${clientExportName(id)} } from ${q(`./clients/${id}.generated.ts`)};`,
    ),
    "",
    `/** ${c(element.name)} (${element.id}), as the design describes it. */`,
    "export const app = defineApp({",
    `  name: ${q(element.id)},`,
    `  title: ${q(config.title)},`,
    targets.length === 0
      ? "  apis: {},"
      : `  apis: {\n${targets.map((id) => `    ${q(id)}: ${clientExportName(id)},`).join("\n")}\n  },`,
    "});",
    "",
  ].join("\n");
}

/** `nginx/jeeves-config.json.template`: the runtime config, filled in at container start. */
export function runtimeConfigTemplate(ctx: GenerateContext): string {
  const apis = Object.fromEntries(
    restClientTargets(ctx).map((t) => [t.target.id, { url: apiPath(t.target.id) }]),
  );
  return `${JSON.stringify({ title: envRef("APP_TITLE"), apis }, null, 2)}\n`;
}

/** `nginx/default.conf.template`: serves the build and forwards each API path to its service. */
export function nginxTemplate(ctx: GenerateContext): string {
  const proxies = restClientTargets(ctx).flatMap((t) => {
    const id = t.target.id;
    return [
      "",
      `    # ${id} (rest-api-client ${t.attachment.id}): /_api/${id}/... goes to the ${id} service.`,
      `    location ${apiPath(id)}/ {`,
      `        set $jeeves_upstream ${envRef(apiEnvName(id, "URL"))};`,
      `        rewrite ^${apiPath(id)}/(.*)$ /$1 break;`,
      "        proxy_pass $jeeves_upstream;",
      ...(t.server.auth === "bearer"
        ? [`        proxy_set_header Authorization "Bearer ${envRef(apiEnvName(id, "TOKEN"))}";`]
        : []),
      "    }",
    ];
  });
  return [
    `# ${HEADER}`,
    `# The nginx image fills in ${envRef("PORT")} and the API_* variables from the environment at startup.`,
    "server {",
    `    listen ${envRef("PORT")};`,
    "    root /usr/share/nginx/html;",
    "    # Docker's DNS, asked again every 10 s so a restarted service's new address is used.",
    "    resolver 127.0.0.11 valid=10s ipv6=off;",
    "",
    "    location = /healthz {",
    "        access_log off;",
    "        default_type text/plain;",
    '        return 200 "ok\\n";',
    "    }",
    "",
    "    location = /jeeves-config.json {",
    '        add_header Cache-Control "no-store";',
    "    }",
    "",
    "    location = /index.html {",
    '        add_header Cache-Control "no-cache";',
    "    }",
    "",
    "    location /assets/ {",
    '        add_header Cache-Control "public, max-age=31536000, immutable";',
    "    }",
    ...proxies,
    "",
    "    # Client-side routes: any other path gets the app.",
    "    location / {",
    "        try_files $uri /index.html;",
    "    }",
    "}",
    "",
  ].join("\n");
}

export function generate(ctx: GenerateContext): GenerateResult {
  const { element, config, dir } = ctx;
  const port = Number(config.port);
  const title = String(config.title);
  const json = (text: string) => JSON.stringify(text).slice(1, -1);
  const files = renderScaffold(SCAFFOLD, dir, {
    appId: element.id,
    appName: element.name.replaceAll("*/", "* /"),
    appDir: dir,
    port: String(port),
    descriptionText: json(`${element.name}: a Jeeves web-app element.`),
    titleText: json(title),
    titleHtml: title.replaceAll("&", "&amp;").replaceAll("<", "&lt;").replaceAll(">", "&gt;"),
  });
  files.push(
    { path: `${dir}/src/jeeves.generated.ts`, contents: wiringSource(ctx), ownership: "generated" },
    {
      path: `${dir}/nginx/default.conf.template`,
      contents: nginxTemplate(ctx),
      ownership: "generated",
    },
    {
      path: `${dir}/nginx/jeeves-config.json.template`,
      contents: runtimeConfigTemplate(ctx),
      ownership: "generated",
    },
  );

  const dependsOn: NonNullable<ComposeService["depends_on"]> = {};
  for (const { connection, peer } of ctx.outgoing) {
    if (connection.kind !== "depends-on" || peer.dir === undefined) continue;
    dependsOn[peer.element.id] = {
      condition: peer.manifest?.id === "http-service" ? "service_healthy" : "service_started",
    };
  }
  const service: ComposeService = {
    build: { context: ".", dockerfile: `${dir}/Dockerfile` },
    environment: {
      PORT: String(port),
      // Compose would read "$NAME" in a value as a variable.
      APP_TITLE: title.replaceAll("$", "$$$$"),
    },
    // An ephemeral host port on loopback: reachable for tests and tools, never from the network.
    ports: [`127.0.0.1::${port}`],
    healthcheck: healthcheck(port),
    restart: "unless-stopped",
    ...(Object.keys(dependsOn).length > 0 && { depends_on: dependsOn }),
  };

  return {
    files,
    compose: { services: { [element.id]: service } },
    runtimeDependencies: [{ element: element.id, name: "@jeeves/web-runtime" }],
  };
}
