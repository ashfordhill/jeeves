import { posix } from "node:path";
import type { GenerateContext, GenerateResult, RestClientTarget } from "@jeeves/template-kit";
import {
  apiEnvName,
  bearerToken,
  clientExportName,
  clientModulePath,
  contractPath,
  restClientTargets,
} from "@jeeves/template-kit";

/** Element templates a client can be generated into, and the runtime flavor each one uses. */
const HOSTS = { "http-service": "service", "web-app": "browser" } as const;
type Host = (typeof HOSTS)[keyof typeof HOSTS];

/** The script that regenerates client types from contracts; `npm run typecheck` runs it first. */
export const TYPES_SCRIPT = { name: "pretypecheck", command: "jeeves-rest-client-types" };

/** The target this client attachment calls, resolved from the design. */
export function targetOf(ctx: GenerateContext): RestClientTarget {
  const target = restClientTargets(ctx).find((t) => t.attachment.id === ctx.attachment?.id);
  if (!target) throw new Error(`${ctx.attachment?.id ?? ctx.element.id} is not a REST client`);
  return target;
}

export function hostOf(ctx: GenerateContext): Host {
  const id = ctx.element.template?.id;
  const host = id && id in HOSTS ? HOSTS[id as keyof typeof HOSTS] : undefined;
  if (!host)
    throw new Error(`A REST client can't be generated into ${id ?? "an untemplated"} element`);
  return host;
}

/** The address compose gives the client: the target service's own port, inside the network. */
export function targetUrl(target: RestClientTarget): string {
  return `http://${target.target.id}:${target.port}`;
}

/** `src/clients/<target>.generated.ts`: the configured client, typed by the contract's types. */
export function clientSource(ctx: GenerateContext): string {
  const target = targetOf(ctx);
  const host = hostOf(ctx);
  const id = target.target.id;
  const q = (value: unknown) => JSON.stringify(value);
  const contract = posix.relative(`${ctx.dir}/src/clients`, contractPath(id));
  const basePath = target.server.basePath.replace(/\/+$/, "");
  const name = target.target.name.replaceAll("*/", "* /");
  const options =
    host === "service"
      ? [
          `  basePath: ${q(basePath || "/")},`,
          `  urlEnv: ${q(apiEnvName(id, "URL"))},`,
          ...(target.server.auth === "bearer"
            ? [`  tokenEnv: ${q(apiEnvName(id, "TOKEN"))},`]
            : []),
        ]
      : [`  baseUrl: () => \`\${apiUrl(${q(id)})}${basePath.replaceAll("`", "")}\`,`];
  return [
    "// Generated by Jeeves from the design. Do not edit: it's rewritten on every generation.",
    `// The types in ./${id}.openapi.ts come from the contract below; \`npm run typecheck\``,
    "// regenerates them, so they follow the contract as it changes.",
    `// @jeeves-contract ${contract}`,
    host === "service"
      ? 'import { serviceRestClient } from "@jeeves/rest-client/service";'
      : 'import { createRestClient } from "@jeeves/rest-client";',
    ...(host === "browser" ? ['import { apiUrl } from "@jeeves/web-runtime";'] : []),
    `import type { paths } from ${q(`./${id}.openapi.ts`)};`,
    "",
    `/**`,
    ` * Typed client for the ${name} API (${id}, base path ${basePath || "/"}). Calls return`,
    " * `{ data, error, response }`; one that gets no response throws a `RestClientError`",
    " * (`code` TIMEOUT or NETWORK).",
    " */",
    `export const ${clientExportName(id)} = ${host === "service" ? "serviceRestClient" : "createRestClient"}<paths>({`,
    `  name: ${q(id)},`,
    ...options,
    `  timeoutMs: ${Number(target.config.timeoutMs)},`,
    `  retries: ${Number(target.config.retries)},`,
    "});",
    "",
  ].join("\n");
}

/**
 * Generates the client module and points the calling element at the target: its address (and
 * token) in the environment, and a `depends_on` that waits for the target to be ready. The
 * calling element's own wiring (http-service, web-app) picks the client up.
 */
export function generate(ctx: GenerateContext): GenerateResult {
  const target = targetOf(ctx);
  const id = target.target.id;
  const environment: Record<string, string> = { [apiEnvName(id, "URL")]: targetUrl(target) };
  if (target.server.auth === "bearer") environment[apiEnvName(id, "TOKEN")] = bearerToken(id);
  return {
    files: [
      {
        path: clientModulePath(ctx.dir, id),
        contents: clientSource(ctx),
        ownership: "generated",
      },
    ],
    compose: {
      services: {
        [ctx.element.id]: {
          environment,
          depends_on: { [id]: { condition: "service_healthy" } },
        },
      },
    },
    runtimeDependencies: [{ element: ctx.element.id, name: "@jeeves/rest-client" }],
    packageScripts: [{ element: ctx.element.id, ...TYPES_SCRIPT }],
  };
}
