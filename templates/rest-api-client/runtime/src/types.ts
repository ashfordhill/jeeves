/**
 * OpenAPI 3.1 contract → TypeScript types in the shape openapi-typescript emits (`paths`,
 * `components`, `operations`), which is what openapi-fetch's `createClient<paths>()` expects.
 *
 * openapi-typescript itself needs the TypeScript 5 compiler API, and generated projects use
 * TypeScript 7, which has none; so this is a small string-based generator for the JSON Schema
 * subset contracts use: `$ref` (local), `type` (including type arrays), `enum`, `const`,
 * `properties`/`required`, `additionalProperties`, `items`/`prefixItems`, `oneOf`/`anyOf`/`allOf`.
 */

type Json = Record<string, unknown>;

const METHODS = ["get", "put", "post", "delete", "options", "head", "patch", "trace"] as const;
const LOCATIONS = ["query", "header", "path", "cookie"] as const;

export class ContractTypesError extends Error {
  readonly problems: string[];

  constructor(source: string, problems: string[]) {
    super(
      `Can't generate client types from ${source}:\n${problems.map((p) => `  - ${p}`).join("\n")}`,
    );
    this.name = "ContractTypesError";
    this.problems = problems;
  }
}

/** Generates the types module for one contract. `source` is named in the header comment. */
export function contractTypes(document: unknown, source: string): string {
  if (!isObject(document)) throw new ContractTypesError(source, ["not an OpenAPI document"]);
  const problems: string[] = [];
  const version = String(document.openapi ?? "");
  if (!/^3\.1\.\d+$/.test(version)) {
    problems.push(`"openapi" must be 3.1.x (got "${version || "nothing"}")`);
  }
  const g = new Generator(document, problems);
  const out = [
    "// Generated by @jeeves/rest-client (jeeves-rest-client-types) from",
    `// ${source}. Do not edit: it's regenerated from the contract by \`npm run typecheck\`.`,
    "",
    g.paths(),
    "export type webhooks = Record<string, never>;",
    g.components(),
    "export type $defs = Record<string, never>;",
    g.operations(),
    "",
  ].join("\n");
  if (problems.length > 0) throw new ContractTypesError(source, problems);
  return out;
}

class Generator {
  private readonly ops: [string, string][] = [];
  private readonly doc: Json;
  private readonly problems: string[];

  constructor(doc: Json, problems: string[]) {
    this.doc = doc;
    this.problems = problems;
  }

  paths(): string {
    const paths = isObject(this.doc.paths) ? this.doc.paths : {};
    const entries: string[] = [];
    const ids = new Set<string>();
    for (const [path, rawItem] of Object.entries(paths)) {
      const item = this.deref(rawItem);
      if (!isObject(item)) continue;
      const shared = asArray(item.parameters);
      const fields = [`parameters: ${this.parameters(shared, [])};`];
      for (const method of METHODS) {
        const operation = item[method];
        if (!isObject(operation)) {
          fields.push(`${method}?: never;`);
          continue;
        }
        const id = typeof operation.operationId === "string" ? operation.operationId : undefined;
        if (!id) {
          this.problems.push(`${method.toUpperCase()} ${path} has no operationId`);
          continue;
        }
        if (ids.has(id)) this.problems.push(`operationId "${id}" is used twice`);
        ids.add(id);
        this.ops.push([id, this.operation(operation, shared)]);
        fields.push(
          `${doc(operation.summary ?? operation.description)}${method}: operations[${q(id)}];`,
        );
      }
      entries.push(`${q(path)}: ${block(fields)};`);
    }
    return `export interface paths ${block(entries)}`;
  }

  operations(): string {
    return `export interface operations ${block(this.ops.map(([id, type]) => `${key(id)}: ${type};`))}`;
  }

  components(): string {
    const components = isObject(this.doc.components) ? this.doc.components : {};
    const section = (title: string, render: (value: unknown) => string) => {
      const values = isObject(components[title]) ? components[title] : {};
      const entries = Object.entries(values).map(
        ([name, value]) =>
          `${doc(isObject(value) ? value.description : undefined)}${key(name)}: ${render(value)};`,
      );
      return entries.length === 0 ? `${title}: never;` : `${title}: ${block(entries)};`;
    };
    return `export interface components ${block([
      section("schemas", (s) => this.schema(s)),
      section("responses", (r) => this.response(r)),
      section("parameters", (p) =>
        this.schema(isObject(this.deref(p)) ? (this.deref(p) as Json).schema : {}),
      ),
      section("requestBodies", (b) => this.requestBody(this.deref(b))),
      section("headers", (h) =>
        this.schema(isObject(this.deref(h)) ? (this.deref(h) as Json).schema : {}),
      ),
      "pathItems: never;",
    ])}`;
  }

  private operation(operation: Json, shared: unknown[]): string {
    const fields = [`parameters: ${this.parameters(shared, asArray(operation.parameters))};`];
    const body = this.deref(operation.requestBody);
    if (isObject(body)) {
      fields.push(`requestBody${body.required === true ? "" : "?"}: ${this.requestBody(body)};`);
    } else {
      fields.push("requestBody?: never;");
    }
    const responses = isObject(operation.responses) ? operation.responses : {};
    const entries = Object.entries(responses).map(([status, response]) => {
      return `${key(status)}: ${this.response(response)};`;
    });
    fields.push(`responses: ${block(entries)};`);
    return block(fields);
  }

  /** Operation-level parameters override path-level ones with the same name and location. */
  private parameters(shared: unknown[], own: unknown[]): string {
    const byKey = new Map<string, Json>();
    for (const raw of [...shared, ...own]) {
      const parameter = this.deref(raw);
      if (!isObject(parameter) || typeof parameter.name !== "string") continue;
      byKey.set(`${parameter.in}:${parameter.name}`, parameter);
    }
    const fields = LOCATIONS.map((location) => {
      const list = [...byKey.values()].filter((p) => p.in === location);
      if (list.length === 0) return `${location}?: never;`;
      const required = list.some((p) => p.required === true || location === "path");
      const entries = list.map((p) => {
        const optional = p.required === true || location === "path" ? "" : "?";
        return `${doc(p.description)}${key(String(p.name))}${optional}: ${this.schema(p.schema)};`;
      });
      return `${location}${required ? "" : "?"}: ${block(entries)};`;
    });
    return block(fields);
  }

  private response(raw: unknown): string {
    if (isObject(raw) && typeof raw.$ref === "string") return this.ref(raw.$ref);
    const response = isObject(raw) ? raw : {};
    const headers = isObject(response.headers) ? response.headers : {};
    const headerEntries = Object.entries(headers).map(([name, value]) => {
      const header = this.deref(value);
      const schema = isObject(header) ? header.schema : undefined;
      const optional = isObject(header) && header.required === true ? "" : "?";
      return `${key(name)}${optional}: ${this.schema(schema)};`;
    });
    headerEntries.push("[name: string]: unknown;");
    const content = this.contentMap(response);
    const contentField = content === "never" ? "content?: never;" : `content: ${content};`;
    return block([`headers: ${block(headerEntries)};`, contentField]);
  }

  /** The `{ "<media type>": T }` map of a request body or response, or `never` without one. */
  private contentMap(holder: unknown): string {
    const content = isObject(holder) && isObject(holder.content) ? holder.content : {};
    const entries = Object.entries(content).map(([media, value]) => {
      const schema = isObject(value) ? value.schema : undefined;
      return `${q(media)}: ${this.schema(schema)};`;
    });
    return entries.length === 0 ? "never" : block(entries);
  }

  private requestBody(holder: unknown): string {
    const map = this.contentMap(holder);
    return map === "never" ? "never" : block([`content: ${map};`]);
  }

  schema(raw: unknown): string {
    if (raw === true || raw === undefined) return "unknown";
    if (raw === false) return "never";
    if (!isObject(raw)) return "unknown";
    if (typeof raw.$ref === "string") return this.ref(raw.$ref);
    if ("const" in raw) return literal(raw.const);
    if (Array.isArray(raw.enum)) return union(raw.enum.map(literal));
    const parts: string[] = [];
    if (Array.isArray(raw.oneOf)) parts.push(union(raw.oneOf.map((s) => this.schema(s))));
    if (Array.isArray(raw.anyOf)) parts.push(union(raw.anyOf.map((s) => this.schema(s))));
    if (Array.isArray(raw.allOf)) {
      parts.push(raw.allOf.map((s) => wrap(this.schema(s))).join(" & "));
    }
    const types = Array.isArray(raw.type) ? raw.type : raw.type === undefined ? [] : [raw.type];
    const implied =
      types.length === 0 && (raw.properties !== undefined || raw.additionalProperties !== undefined)
        ? ["object"]
        : types.length === 0 && raw.items !== undefined
          ? ["array"]
          : types;
    if (implied.length > 0) parts.push(union(implied.map((t) => this.typed(String(t), raw))));
    if (parts.length === 0) return "unknown";
    return parts.length === 1 ? (parts[0] as string) : parts.map(wrap).join(" & ");
  }

  private typed(type: string, schema: Json): string {
    switch (type) {
      case "string":
        return "string";
      case "integer":
      case "number":
        return "number";
      case "boolean":
        return "boolean";
      case "null":
        return "null";
      case "array": {
        if (Array.isArray(schema.prefixItems)) {
          const items = schema.prefixItems.map((s) => this.schema(s));
          const rest = schema.items === false ? "" : `, ...${wrap(this.schema(schema.items))}[]`;
          return `[${items.join(", ")}${rest}]`;
        }
        return `${wrap(this.schema(schema.items))}[]`;
      }
      case "object": {
        const properties = isObject(schema.properties) ? schema.properties : {};
        const required = new Set(asArray(schema.required).map(String));
        const entries = Object.entries(properties).map(([name, value]) => {
          const optional = required.has(name) ? "" : "?";
          const description = isObject(value) ? value.description : undefined;
          return `${doc(description)}${key(name)}${optional}: ${this.schema(value)};`;
        });
        const extra = schema.additionalProperties;
        if (extra !== undefined && extra !== false) {
          const value = this.schema(extra);
          // An index signature must admit every named property's type.
          entries.push(`[key: string]: ${entries.length > 0 ? "unknown" : value};`);
        }
        return entries.length === 0
          ? extra === false
            ? "Record<string, never>"
            : "Record<string, unknown>"
          : block(entries);
      }
      default:
        this.problems.push(`unknown schema type "${type}"`);
        return "unknown";
    }
  }

  private ref(ref: string): string {
    const match = /^#\/components\/([A-Za-z]+)\/([^/]+)$/.exec(ref);
    if (!match) {
      this.problems.push(`$ref ${ref} isn't supported; use #/components/<section>/<name>`);
      return "unknown";
    }
    const [, section, name] = match as unknown as [string, string, string];
    const components = isObject(this.doc.components) ? this.doc.components : {};
    if (
      !isObject(components[section]) ||
      !(unescapePointer(name) in (components[section] as Json))
    ) {
      this.problems.push(`$ref ${ref} points at nothing`);
      return "unknown";
    }
    return `components[${q(section)}][${q(unescapePointer(name))}]`;
  }

  /** Follows a local `$ref` to the object it names. */
  private deref(value: unknown, seen = new Set<string>()): unknown {
    if (!isObject(value) || typeof value.$ref !== "string") return value;
    const ref = value.$ref;
    if (seen.has(ref) || !ref.startsWith("#/")) return undefined;
    seen.add(ref);
    let target: unknown = this.doc;
    for (const segment of ref.slice(2).split("/")) {
      target = isObject(target) ? target[unescapePointer(segment)] : undefined;
    }
    return this.deref(target, seen);
  }
}

function unescapePointer(segment: string): string {
  return segment.replaceAll("~1", "/").replaceAll("~0", "~");
}

function block(lines: string[]): string {
  if (lines.length === 0) return "Record<string, never>";
  const body = lines.map((line) => line.replaceAll("\n", "\n  "));
  return `{\n  ${body.join("\n  ")}\n}`;
}

function union(types: string[]): string {
  const unique = [...new Set(types)];
  if (unique.length === 0) return "never";
  return unique.length === 1 ? (unique[0] as string) : unique.map(wrap).join(" | ");
}

/** Parenthesizes a union or intersection so it can be combined or suffixed with `[]`. */
function wrap(type: string): string {
  return isAtomic(type) ? type : `(${type})`;
}

/** A name, a reference, a literal, or one balanced `{ ... }` or `[ ... ]`. */
function isAtomic(type: string): boolean {
  if (/^(?:[\w$.]+|"(?:[^"\\]|\\.)*")(?:\["(?:[^"\\]|\\.)*"\])*$/.test(type)) return true;
  const open = type[0];
  if (open !== "{" && open !== "[") return false;
  let depth = 0;
  for (let i = 0; i < type.length; i += 1) {
    const char = type[i];
    if (char === '"') {
      for (i += 1; i < type.length && type[i] !== '"'; i += 1) if (type[i] === "\\") i += 1;
      continue;
    }
    if (char === "{" || char === "[" || char === "(") depth += 1;
    if (char === "}" || char === "]" || char === ")") {
      depth -= 1;
      if (depth === 0) return i === type.length - 1;
    }
  }
  return false;
}

function literal(value: unknown): string {
  return value === null || ["string", "number", "boolean"].includes(typeof value)
    ? JSON.stringify(value)
    : "unknown";
}

function doc(text: unknown): string {
  if (typeof text !== "string" || text.trim() === "") return "";
  return `/** ${text.trim().replaceAll("*/", "* /").replaceAll("\n", " ")} */\n`;
}

function q(name: string): string {
  return JSON.stringify(name);
}

/** A property key: bare when it's an identifier, quoted otherwise (as openapi-typescript does). */
function key(name: string): string {
  return /^(?:[A-Za-z_$][\w$]*|[1-9]\d*)$/.test(name) ? name : JSON.stringify(name);
}

function isObject(value: unknown): value is Json {
  return typeof value === "object" && value !== null && !Array.isArray(value);
}

function asArray(value: unknown): unknown[] {
  return Array.isArray(value) ? value : [];
}
