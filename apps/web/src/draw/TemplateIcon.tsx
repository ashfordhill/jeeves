/** Tabler icons named by template manifests (`card.icon`). Unknown names fall back to a box. */
import {
  type Icon,
  IconActivity,
  IconApi,
  IconArchive,
  IconArrowsSplit,
  IconBolt,
  IconBox,
  IconBrowser,
  IconChartBar,
  IconCpu,
  IconCreditCard,
  IconDatabase,
  IconDeviceDesktop,
  IconDeviceMobile,
  IconList,
  IconLock,
  IconMail,
  IconPhoto,
  IconPlug,
  IconPlugConnected,
  IconPuzzle,
  IconQuestionMark,
  IconRepeat,
  IconRoute,
  IconSearch,
  IconServer,
  IconSettings,
  IconShield,
  IconWorld,
} from "@tabler/icons-react";

const ICONS: Record<string, Icon> = {
  api: IconApi,
  browser: IconBrowser,
  database: IconDatabase,
  "plug-connected": IconPlugConnected,
  server: IconServer,
  repeat: IconRepeat,
  settings: IconSettings,
  activity: IconActivity,
  archive: IconArchive,
  "arrows-split": IconArrowsSplit,
  bolt: IconBolt,
  "chart-bar": IconChartBar,
  cpu: IconCpu,
  "credit-card": IconCreditCard,
  "device-desktop": IconDeviceDesktop,
  "device-mobile": IconDeviceMobile,
  list: IconList,
  lock: IconLock,
  mail: IconMail,
  photo: IconPhoto,
  plug: IconPlug,
  puzzle: IconPuzzle,
  route: IconRoute,
  search: IconSearch,
  shield: IconShield,
  world: IconWorld,
};

export function TemplateIcon({ name, size = 20 }: { name: string | undefined; size?: number }) {
  const Glyph = name ? (ICONS[name] ?? IconBox) : IconQuestionMark;
  return <Glyph size={size} stroke={2} aria-hidden />;
}
